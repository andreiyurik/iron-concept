#!/usr/bin/env python3
"""Requirement identifiers for the normative specs.

A requirement is a block (list item, paragraph, or table row) in
docs/specs/*.md that contains the word MUST. Each one carries a marker:

    `REQ-CMD-003 integration`

The identifier is permanent; the word after it is the test level that
proves the requirement (unit | integration | sim | field | ci | review).
The marker is the single source of truth — edit the level there.

    python3 scripts/requirements.py          assign missing ids, rewrite the index
    python3 scripts/requirements.py --check  fail if anything is missing or stale

The index (docs/requirements.md) is generated. Never edit it by hand.
"""
import glob
import os
import re
import sys

# spec file -> (prefix, default test level)
SPECS = {
    "agent-interface": ("AGT", "integration"),
    "alarm-engine": ("ALM", "unit"),
    "architecture": ("ARC", "review"),
    "cli": ("CLI", "integration"),
    "command-path": ("CMD", "integration"),
    "config-lifecycle": ("CFG", "integration"),
    "deployment": ("DEP", "integration"),
    "device-types": ("TYP", "unit"),
    "edge-agent": ("EDG", "unit"),
    "expressions": ("EXP", "unit"),
    "extensions": ("EXT", "integration"),
    "field-verification": ("FLD", "field"),
    "historian": ("HIS", "integration"),
    "operations": ("OPS", "ci"),
    "protocol-drivers": ("DRV", "integration"),
    "read-write-separation": ("RWS", "integration"),
    "security": ("SEC", "integration"),
    "tag-model": ("TAG", "unit"),
    "testing": ("TST", "review"),
    "transport": ("TRN", "integration"),
    "visual-system": ("VIS", "unit"),
}
SKIP = {"plc-runtime"}  # exploration, not normative
LEVELS = {"unit", "integration", "sim", "field", "ci", "review"}
INDEX = "docs/requirements.md"
MARK = re.compile(r"`(REQ-([A-Z]{3})-(\d{3})) ([a-z]+)`")
MUST = re.compile(r"\bMUST\b")
ITEM = re.compile(r"^\s*([-*]|\d+\.)\s")


def blocks(lines):
    """Yield (first, last) line indexes of each prose block outside code."""
    start, fenced, front = None, False, False
    for i, line in enumerate(lines + [""]):
        s = line.strip()
        if i == 0 and s == "---":
            front = True
            continue
        if front:
            front = s != "---"
            continue
        if s.startswith("```"):
            if start is not None:
                yield start, i - 1
                start = None
            fenced = not fenced
            continue
        if fenced:
            continue
        boundary = not s or s.startswith("#")
        new_unit = ITEM.match(line) or s.startswith("|")
        if start is not None and (boundary or new_unit):
            yield start, i - 1
            start = None
        if not boundary and start is None:
            start = i


def process(name, write):
    prefix, default = SPECS[name]
    path = f"docs/specs/{name}.md"
    lines = open(path, encoding="utf-8").read().split("\n")
    used = [int(m.group(3)) for l in lines for m in MARK.finditer(l)]
    nxt = max(used, default=0) + 1
    rows, missing = [], 0
    for a, b in list(blocks(lines)):
        text = " ".join(l.strip() for l in lines[a : b + 1])
        if not MUST.search(text):
            continue
        m = MARK.search(text)
        if not m:
            missing += 1
            if not write:
                continue
            mark = f"`REQ-{prefix}-{nxt:03d} {default}`"
            nxt += 1
            last = lines[b].rstrip()
            if last.endswith("|"):
                lines[b] = last[:-1].rstrip() + f" {mark} |"
            else:
                lines[b] = f"{last} {mark}"
            text = " ".join(l.strip() for l in lines[a : b + 1])
            m = MARK.search(text)
        clean = MARK.sub("", text)
        clean = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", clean)
        clean = re.sub(r"^([-*]|\d+\.)\s+", "", clean.strip(" |"))
        clean = re.sub(r"\s+", " ", clean.replace("|", "/")).strip()
        if len(clean) > 150:
            clean = clean[:147].rstrip() + "…"
        rows.append((m.group(1), m.group(4), name, clean))
    if write:
        open(path, "w", encoding="utf-8").write("\n".join(lines))
    return rows, missing


def render(rows):
    out = [
        "# Requirements Index",
        "",
        "> **Generated by `scripts/requirements.py` — do not edit.** The specs are",
        "> the source: each requirement carries its identifier and test level",
        "> inline. This page exists so a requirement can be found by identifier",
        "> and so a test can name what it proves.",
        "",
        f"{len(rows)} requirements. Test levels are defined in",
        "[specs/testing.md](specs/testing.md); `ci` is a static check, `review`",
        "is not automatically testable.",
        "",
        "| Identifier | Level | Spec | Requirement |",
        "|---|---|---|---|",
    ]
    for rid, level, name, text in sorted(rows):
        out.append(f"| `{rid}` | {level} | [{name}](specs/{name}.md) | {text} |")
    return "\n".join(out) + "\n"


def main():
    check = "--check" in sys.argv
    errors, rows = [], []
    for path in sorted(glob.glob("docs/specs/*.md")):
        name = os.path.basename(path)[:-3]
        if name in SKIP:
            continue
        if name not in SPECS:
            errors.append(f"{path}: no prefix in scripts/requirements.py")
            continue
        r, missing = process(name, write=not check)
        rows += r
        if check and missing:
            errors.append(f"{path}: {missing} MUST block(s) without an identifier")
    ids = [r[0] for r in rows]
    for rid in {i for i in ids if ids.count(i) > 1}:
        errors.append(f"duplicate identifier {rid}")
    for rid, level, name, _ in rows:
        if level not in LEVELS:
            errors.append(f"{rid}: unknown test level '{level}'")
        if rid.split("-")[1] != SPECS[name][0]:
            errors.append(f"{rid}: wrong prefix for {name}.md")
    index = render(rows)
    if check:
        current = open(INDEX, encoding="utf-8").read() if os.path.exists(INDEX) else ""
        if current != index:
            errors.append(f"{INDEX} is stale — run scripts/requirements.py")
    else:
        open(INDEX, "w", encoding="utf-8").write(index)
    # conformance vectors may only cite identifiers that exist
    known = set(ids)
    for f in glob.glob("conformance/**/*.yaml", recursive=True):
        for i, line in enumerate(open(f, encoding="utf-8"), 1):
            for rid in re.findall(r"REQ-[A-Z]{3}-\d{3}", line):
                if rid not in known:
                    errors.append(f"{f}:{i}: unknown requirement {rid}")
    if errors:
        print(f"❌ {len(errors)} requirement problem(s):")
        for e in errors:
            print("  " + e)
        sys.exit(1)
    print(f"✅ {len(rows)} requirements, all identified" + ("" if check else f"; wrote {INDEX}"))


if __name__ == "__main__":
    main()
